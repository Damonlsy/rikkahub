    suspend fun generateSuggestion(
        conversationId: Uuid,
        conversation: Conversation,
    ) = withContext(Dispatchers.IO) {
        runCatching {
            val settings = settingsStore.settingsFlow.first()
            if (!settings.enableSuggestion) return@runCatching
            val model = settings.findModelById(settings.fastModelId)
                ?: return@runCatching
            val provider = model.findProvider(settings.providers) ?: return@runCatching

            sessionManager.get(conversationId)?.let { session ->
                updateConversation(
                    conversationId,
                    session.state.value.copy(chatSuggestions = emptyList())
                )
            }

            val providerHandler = providerManager.getProviderByType(provider)
            val result = providerHandler.generateText(
                providerSetting = provider,
                messages = listOf(
                    UIMessage.user(
                        settings.suggestionPrompt.applyPlaceholders(
                            "locale" to Locale.getDefault().displayName,
                            "content" to conversation.currentMessages
                                .takeLast(8).joinToString("\n\n") { it.summaryAsText(maxLength = 500) }),
                    )
                ),
                params = backgroundTextGenerationParams(model, conversationId, settings.fastModelReasoningLevel),
            )
            val suggestions =
                result.message.toText().split("\n").map { it.trim() }
                    .filter { it.isNotBlank() }

            val latestConversation = conversationRepo.getConversationById(conversationId)
                ?: sessionManager.get(conversationId)?.state?.value
                ?: conversation
            saveConversation(
                conversationId,
                latestConversation.copy(
                    chatSuggestions = suggestions.take(
                        10
                    )
                )
            )
        }.onFailure {
            it.printStackTrace()
        }
    }

    // ---- 压缩对话历史 ----

    suspend fun compressConversation(
        conversationId: Uuid,
        conversation: Conversation,
        additionalPrompt: String,
        targetTokens: Int,
        keepRecentMessages: Int = 32
    ): Result<Unit> = runCatching {
        val settings = settingsStore.settingsFlow.first()
        val model = settings.findModelById(settings.compressModelId)
            ?: settings.getCurrentChatModel()
            ?: throw IllegalStateException("No model available for compression")
        val provider = model.findProvider(settings.providers)
            ?: throw IllegalStateException("Provider not found")

        val providerHandler = providerManager.getProviderByType(provider)

        val maxMessagesPerChunk = 256
        val allMessages = conversation.currentMessages

        // 压缩不再改写 messageNodes：聊天记录原样保留，只记录「摘要 + 折叠点」，
        // 发给模型前由 CompressedContextTransformer 把折叠点之前的历史换成摘要。
        // 再压一次时只压缩上一次折叠点之后的新消息，旧摘要直接拼接在前面。
        val previous = compressionStore.get(conversationId)
        val historyFrom = previous?.let { prev ->
            allMessages.indexOfFirst { it.id.toString() == prev.boundaryMessageId } + 1
        } ?: 0
        val uncompressedMessages = if (historyFrom in 1..allMessages.size) {
            allMessages.subList(historyFrom, allMessages.size)
        } else {
            allMessages
        }

        val messagesToCompress: List<UIMessage>

        if (keepRecentMessages > 0 && uncompressedMessages.size > keepRecentMessages) {
            messagesToCompress = uncompressedMessages.dropLast(keepRecentMessages)
        } else if (keepRecentMessages > 0) {
            // Not enough messages to compress while keeping recent ones
            throw IllegalStateException(context.getString(R.string.chat_page_compress_not_enough_messages))
        } else {
            messagesToCompress = uncompressedMessages
        }

        if (messagesToCompress.isEmpty()) {
            throw IllegalStateException(context.getString(R.string.chat_page_compress_not_enough_messages))
        }

        fun splitMessages(messages: List<UIMessage>): List<List<UIMessage>> {
            if (messages.size <= maxMessagesPerChunk) return listOf(messages)
            val mid = messages.size / 2
            val left = splitMessages(messages.subList(0, mid))
            val right = splitMessages(messages.subList(mid, messages.size))
            return left + right
        }

        suspend fun compressMessages(messages: List<UIMessage>): String {
            val contentToCompress = messages.joinToString("\n\n") { it.summaryAsText(maxLength = 2000) }
            val prompt = settings.compressPrompt.applyPlaceholders(
                "content" to contentToCompress,
                "target_tokens" to targetTokens.toString(),
                "additional_context" to if (additionalPrompt.isNotBlank()) {
                    "Additional instructions from user: $additionalPrompt"
                } else "",
                "locale" to Locale.getDefault().displayName
            )

            val result = providerHandler.generateText(
                providerSetting = provider,
                messages = listOf(UIMessage.user(prompt)),
                params = backgroundTextGenerationParams(model, conversationId),
            )

            return result.message.toText().trim().takeIf { it.isNotBlank() }
                ?: throw IllegalStateException("Failed to generate compressed summary")
        }

        val compressedSummaries = coroutineScope {
            splitMessages(messagesToCompress)
                .map { chunk -> async { compressMessages(chunk) } }
                .awaitAll()
        }

        // 上一次的摘要覆盖的是更早的历史，直接拼在前面；边界丢了说明是全量重压，就不要重复拼
        val mergedSummary = buildList {
            if (historyFrom > 0 && previous != null && previous.summary.isNotBlank()) {
                add(previous.summary)
            }
            addAll(compressedSummaries)
        }.joinToString("\n\n")

        val boundary = messagesToCompress.last()
        compressionStore.set(
            conversationId,
            CompressedContext(
                summary = mergedSummary,
                boundaryMessageId = boundary.id.toString(),
                compressedCount = messagesToCompress.size,
            )
        )

        appendCompressionNotice(
            conversationId = conversationId,
            compressedCount = messagesToCompress.size,
            keptCount = uncompressedMessages.size - messagesToCompress.size,
        )
    }

    /**
     * 压缩成功后往聊框里追加一条「拍一拍」样式的居中小胶囊，给用户一个明确的完成反馈。
     *
     * 打了 isSynthetic：生成时会被 [me.rerere.rikkahub.data.ai.GenerationLoop] 过滤掉，
     * 不会发给模型；聊天记录里这条永远保留，用户也能看见压缩过。
     * 正在生成时不动 messageNodes（会和流式消息抢索引），直接跳过这次提示。
     */
    private suspend fun appendCompressionNotice(
        conversationId: Uuid,
        compressedCount: Int,
        keptCount: Int,
    ) {
        if (sessionManager.get(conversationId)?.isGenerating == true) {
            Logging.log(TAG, "appendCompressionNotice: skip, conversation is generating")
            return
        }
        val text = context.getString(R.string.chat_compress_notice, compressedCount, keptCount)
        val notice = UIMessage(
            role = MessageRole.ASSISTANT,
            parts = buildPatParts(text),
        ).copy(isSynthetic = true)

        runCatching {
            val current = getConversationFlow(conversationId).value
            val updated = current.copy(
                messageNodes = current.messageNodes + notice.toMessageNode(),
                updateAt = Instant.now(),
            )
            updateConversationState(conversationId) { updated }
            saveConversation(conversationId, updated)
        }.onFailure {
            Logging.log(TAG, "appendCompressionNotice: $it")
            Logging.log(TAG, it.stackTraceToString())
        }
    }

    /**
     * 通话挂断后追加一条真正的通话记录消息。
     *
     * 不打 isSynthetic：这条要持久化并展示给用户（GenerationLoop 只在生成时读它，不发给模型）。
     * 挂断瞬间 AI 可能正在回复，先等生成结束再写，避免和流式写入抢 conversation。
     */
    suspend fun appendCallRecord(
        conversationId: Uuid,
        durationSeconds: Long,
    ) {
        var waitedMs = 0L
        while (sessionManager.get(conversationId)?.isGenerating == true && waitedMs < 60_000L) {
            delay(500)
            waitedMs += 500
        }
        if (sessionManager.get(conversationId)?.isGenerating == true) {
            Logging.log(TAG, "appendCallRecord: skip, conversation is still generating")
            return
        }
        val text = context.getString(R.string.chat_call_record, formatCallDuration(durationSeconds))
        val record = UIMessage(
            role = MessageRole.ASSISTANT,
            parts = buildCallParts(text),
        )

        runCatching {
            val current = getConversationFlow(conversationId).value
            val updated = current.copy(
                messageNodes = current.messageNodes + record.toMessageNode(),
                updateAt = Instant.now(),
            )
            updateConversationState(conversationId) { updated }
            saveConversation(conversationId, updated)
        }.onFailure {
            Logging.log(TAG, "appendCallRecord: $it")
            Logging.log(TAG, it.stackTraceToString())
        }
    }

    /** 当前会话的上下文压缩状态，null 表示没有压缩过 */
